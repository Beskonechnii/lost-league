"use client";

import { useState, type ReactNode } from "react";
import { Pagination } from "@/components/pouf/pagination";

/**
 * Колода турниров одного состояния на витрине: на экране одна карточка, соседи — по стрелке.
 *
 * Листаются карточки ВНУТРИ состояния, а сами три состояния (идёт · приём заявок · завершён)
 * остаются на экране разом: их всегда три, они и так видны, и прятать соседей за стрелку — терять
 * обзор ради экономии, которой нет (ТЗ 23, допущение по листалке).
 *
 * Карточки приезжают готовыми с сервера и все лежат в разметке — стрелка только показывает
 * следующую, догрузки по клику нет. Непоказанные скрыты `hidden`, а не выкинуты: так имя каждого
 * турнира есть в отданном HTML, и переключение не стоит перерисовки.
 *
 * Стрелки берём у `Pagination` Кита — это его штатный элемент для «листать список». Своей строки
 * стрелок не заводим; при одной карточке она сама возвращает `null`, поэтому кнопки, ведущей
 * в никуда, на экране не бывает.
 */
export function SlotDeck({ cards }: { cards: ReactNode[] }) {
  const [page, setPage] = useState(1);
  const i = Math.min(page, cards.length) - 1;

  return (
    <>
      {cards.map((card, n) => (
        // `contents` — обёртка не должна становиться лишним уровнем раскладки: карточка обязана
        // остаться прямым элементом колонки, иначе не растянется на её высоту.
        <div key={n} className={n === i ? "contents" : "hidden"}>
          {card}
        </div>
      ))}
      <Pagination page={i + 1} pages={cards.length} onPage={setPage} />
    </>
  );
}
