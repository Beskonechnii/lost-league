/** Перечисление ссылок через запятую — им набраны колонки «ждёт параметры» и «кладёт в vars». */
function Refs({ names }: { names: string[] }) {
  if (!names.length) return <>—</>;
  return (
    <>
      {names.map((name, i) => (
        <span key={name}>
          {i ? ", " : ""}
          <C>{name}</C>
        </span>
      ))}
    </>
  );
}
