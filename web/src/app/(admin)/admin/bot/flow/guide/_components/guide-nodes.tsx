import type { ReactNode } from "react";
import { Heading } from "@/components/pouf/text";
import { makeNode, portsOf, NODE_KINDS } from "@/lib/bot-flow/editor";
import type { FlowNodeType } from "@/lib/bot-flow/types";
import { Bullets, C, Example, Fields, GuideSection, Note, P } from "./guide-bits";

/* Справочник типов нод для гайда оператора (Э8).
 *
 * Подписи типов и их выходы берутся из тех же функций, которыми живёт редактор (`NODE_KINDS`,
 * `portsOf`), а не переписаны сюда руками: гайд, разошедшийся с реестром, врёт — а это хуже, чем
 * отсутствие гайда. Руками написано только то, чего в коде нет словами: когда ноду брать, когда не
 * брать и что будет, если поле оставить пустым.
 */

/** Подпись типа в палитре — та же, что видно на кнопке над канвасом. */
const label = (type: FlowNodeType) => NODE_KINDS.find((k) => k.type === type)?.label ?? type;

/** Выходы типа — ровно те, что нарисует канвас у свежей ноды (кнопки добавляют свои сверху). */
const ports = (type: FlowNodeType) => portsOf(makeNode(type, "x", 0, 0)).map((p) => p.label);

function NodeBlock({
  type,
  what,
  take,
  skip,
  fields,
  outs,
  children,
}: {
  type: FlowNodeType;
  /** Что нода делает — одной-двумя фразами. */
  what: ReactNode;
  /** Когда её брать. */
  take: ReactNode;
  /** Когда НЕ брать — это чаще спасает, чем список возможностей. */
  skip: ReactNode;
  /** Поля инспектора, свои у этого типа. */
  fields?: { name: ReactNode; children: ReactNode }[];
  /** Что происходит по каждому выходу — в порядке `portsOf`. */
  outs: ReactNode;
  /** Пример из живого графа. */
  children?: ReactNode;
}) {
  return (
    <div className="space-y-2.5 border-t border-hairline pt-4 first:border-t-0 first:pt-0">
      <Heading level={3}>
        {label(type)} <span className="font-mono text-[14px] font-bold text-muted">{type}</span>
      </Heading>
      <P>{what}</P>
      <Bullets
        items={[
          <>
            <b>Брать, когда</b> {take}
          </>,
          <>
            <b>Не брать, когда</b> {skip}
          </>,
        ]}
      />
      {fields && fields.length > 0 && (
        <>
          <p className="text-[11px] font-black uppercase tracking-[0.4px] text-muted">Поля инспектора</p>
          <Fields items={fields} />
        </>
      )}
      <p className="text-[11px] font-black uppercase tracking-[0.4px] text-muted">
        Выходы: {ports(type).length ? ports(type).map((p) => `«${p}»`).join(", ") : "нет"}
      </p>
      <P>{outs}</P>
      {children}
    </div>
  );
}

