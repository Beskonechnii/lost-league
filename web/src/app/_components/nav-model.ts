import type { IconName } from "@/components/pouf/Icon";

// Форма данных сайдбара — одна на обе группы маршрутов. Лежит отдельным файлом, потому что её
// читают и сервер (layout собирает пункты по правам), и клиент (сама колонка): тип в клиентском
// модуле утянул бы за собой "use client", а тип в серверном — "server-only".

export type NavItem = {
  href: string;
  label: string;
  icon: IconName;
  /** Подсказка при наведении: зачем этот раздел. */
  hint?: string;
  /** Счётчик у пункта (очередь модерации). 0 и undefined не рисуются. */
  badge?: number;
  /** «В разработке»: место в списке держится, экрана ещё нет. */
  soon?: boolean;
  /** Дополнительные префиксы, на которых пункт считается активным. */
  match?: string[];
};

/** Секция колонки: подписанная группа пунктов («Лига», «Модерация», «Кабинет»). */
export type NavSection = { title: string; items: NavItem[] };

/** Кто вошёл — для профиль-блока в шапке колонки. null = гость. */
export type NavAccount = {
  name: string;
  /** Подпись под именем: роль в лиге и, если есть, команда. */
  role: string;
  /** Цвет точки у роли — владелец/админ/игрок различаются с одного взгляда. */
  dot: string;
  /** Две буквы на аватар, когда фото нет. */
  initials: string;
  photo: string | null;
};
