import type { linkablePlayers } from "@/lib/account";

// Карточка игрока ростера, к которому ещё можно привязаться, — форма строки из `linkablePlayers()`.
//
// Тип выводится из самой выборки, а не выписан руками: набор полей там расширенный (ветка «я уже
// участник лиги» подтягивает известное о найденном игроке и доспрашивает только остальное), и
// вторая, рукописная копия молча разъезжалась бы с select'ом при каждой правке.
//
// Импорт только типовой — `@/lib/account` помечен `server-only`, но `import type` стирается при
// сборке и в клиентский бандл анкеты не попадает.
export type LinkablePlayer = Awaited<ReturnType<typeof linkablePlayers>>[number];
