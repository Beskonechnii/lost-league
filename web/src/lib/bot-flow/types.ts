// Чистая часть нодового флоу бота: из чего состоит граф диалога. Ни БД, ни Telegram — только типы
// и мелкие проверки над ними, поэтому файл читают и интерпретатор (`run.ts`), и будущий редактор
// (`BOT-FLOW-PLAN.md`, Э2), и валидатор (Э3).
//
// **Граф управляет навигацией, а не бизнес-логикой.** Нода решает, что бот скажет, какие кнопки
// покажет, куда шагнёт и какие переменные накопит. Тяжёлое (регистрация в лиге, заказ встречи,
// выдача кода входа) остаётся в TS и подключается нодами `action` и `subflow` — с объявленными
// входами и выходами. Полноценный визуальный язык программирования не строим.
//
// **Ключ перехода — текст кнопки.** Клавиатура у бота reply, а не inline: ответ приезжает обычным
// сообщением. Значит ребро подписано ровно тем, что написано на кнопке, — и одинаковые подписи в
// одной ноде это ошибка графа (проверит валидатор Э3), а не мелочь.

/** Идентификатор ноды. Строкой, а не числом: он же лежит в `BotSession.flowNode`. */
export type NodeId = string;

/**
 * Ссылка на значение: `vars.ник`, `ctx.известен`, `settings.remind_before`. Три области различаются
 * префиксом — `vars` собрано этим диалогом, `ctx` вычислено по сообщению (только чтение),
 * `settings` взято из реестра таймингов и текстов уведомлений (`bot-settings.ts`).
 */
export type FlowRef = string;

/** Что сравниваем. `есть`/`нет` — про пустоту значения, остальное — про само значение. */
export type FlowOp = "=" | "≠" | ">" | "<" | "есть" | "нет";

/** Условие над переменными: им ветвится нода `if` и прячется кнопка. */
export type FlowCondition = {
  left: FlowRef;
  op: FlowOp;
  /** С чем сравниваем. У `есть`/`нет` не нужен. */
  right?: string;
};

/**
 * Кнопка на клавиатуре — она же ребро графа.
 *
 * `next: null` — кнопка показывается, а перехода у неё нет. С Э6 это дыра, а не шов: старого пути
 * за графом больше нет, и валидатор такую кнопку не пускает в эфир. Интерпретатор на ней начинает
 * разговор заново — молча уронить человека хуже, чем показать ему меню.
 */
export type FlowButton = {
  label: string;
  next: NodeId | null;
  /** Показывать кнопку, только если условие верно. Нет условия — показываем всегда. */
  when?: FlowCondition | null;
  /** Номер строки на клавиатуре: кнопки с одним номером встают в ряд. Нет номера — своя строка. */
  row?: number;
};

/** Проверка ответа у ноды `ask`. `regex` — своё выражение оператора, остальное — готовые виды. */
export type FlowCheck = {
  kind: "любой" | "число" | "ссылка" | "телеграм" | "regex";
  pattern?: string;
  /** Что сказать, когда ответ не прошёл. Пусто — скажем общей фразой. */
  message?: string;
};

/**
 * Что ждущая нода делает со **служебной кнопкой** — подписью перехвата уровня флоу, прилетевшей
 * посреди разговора (Э6; раньше это были массивы `SERVICE` внутри модулей и связка `if` в
 * `handleMessage`).
 *
 * `перехват`  — перехват срабатывает: разговор бросается и уходит туда, куда велит перехват.
 *               Годится там, где терять нечего, — меню, экраны справок, выбор из списка.
 * `повторить` — не бросаем начатое: бот говорит, что сперва надо закончить, и повторяет вопрос,
 *               на котором стоит разговор. Так вёл себя старый путь посреди квиза, и так должны
 *               вести себя ноды-модули: анкета на седьмом вопросе не пропадает от случайного
 *               нажатия кнопки, оставшейся на клавиатуре.
 *
 * `/start` и `/cancel` сильнее любой политики (`FlowIntercept.force`): ими человек и бросает
 * начатое, и другого способа выйти у него нет.
 */
export type ServicePolicy = "перехват" | "повторить";

/** Общее у всех нод: id и место на канвасе редактора (Э2). */
type NodeBase = {
  id: NodeId;
  /** Координаты на канвасе. Интерпретатору не нужны, но живут в том же документе. */
  x?: number;
  y?: number;
  /** Подпись ноды в редакторе — человеку, а не боту. */
  title?: string;
};

/**
 * Точка входа графа. Своих полей нет: чем именно в этот флоу попадают — командой, ссылкой или
 * кнопкой из рассылки — записано в `entry` документа (Э7), одной записью на весь граф. Поле
 * `payload` у ноды жило с Э1 и не читалось рантаймом ни дня после Э7 — убрано, чтобы редактор не
 * предлагал настройку, которая ни на что не влияет.
 */
export type StartNode = NodeBase & { type: "start"; next: NodeId | null };

/** Реплика и клавиатура. Ответа не ждёт — шагает дальше сразу. */
export type MessageNode = NodeBase & {
  type: "message";
  text: string;
  buttons?: FlowButton[];
  next: NodeId | null;
};

/** Вопрос: ждёт ответ, кладёт его в переменную `vars.<var>`. */
export type AskNode = NodeBase & {
  type: "ask";
  text: string;
  /** Имя переменной без префикса: `ник` → `vars.ник`. */
  var: string;
  /** Варианты кнопками; у каждого свой выход. Пусто — свободный ответ. */
  buttons?: FlowButton[];
  check?: FlowCheck | null;
  /** Куда идти с любым другим ответом. `null` — переспросить этой же нодой. */
  else: NodeId | null;
  /** Что делать со служебной кнопкой. Нет поля — `перехват` (`servicePolicyOf`). */
  service?: ServicePolicy;
};

/** Набор кнопок с именованными выходами — частный случай `ask` без переменной. */
export type MenuNode = NodeBase & {
  type: "menu";
  text: string;
  buttons: FlowButton[];
  /** Куда идти с непонятым ответом. `null` с Э6 — дыра: валидатор такую ноду не выпустит в эфир. */
  else?: NodeId | null;
  /** Что делать со служебной кнопкой. Нет поля — `перехват` (`servicePolicyOf`). */
  service?: ServicePolicy;
};

/** Развилка по условию. */
export type IfNode = NodeBase & { type: "if"; cond: FlowCondition; then: NodeId | null; else: NodeId | null };

/** Вызов зарегистрированной TS-функции (`actions.ts`). Выходы — `ок` и `ошибка`. */
export type ActionNode = NodeBase & {
  type: "action";
  action: string;
  params?: Record<string, string>;
  ok: NodeId | null;
  fail: NodeId | null;
};

/**
 * Передача управления рукописному модулю целиком, пока тот не скажет `done` (`subflows.ts`).
 * Выход «отменено» — модуль не взялся за работу (не капитан, анкет нет, править нечего).
 */
export type SubflowNode = NodeBase & {
  type: "subflow";
  flow: string;
  /** Чем кормим модуль: значения с подстановками, как у действия (`турнир: "{vars.турнир_id}"`). */
  params?: Record<string, string>;
  done: NodeId | null;
  cancel: NodeId | null;
  /** Что делать со служебной кнопкой. Нет поля — `повторить`: внутри модуля есть что терять. */
  service?: ServicePolicy;
};

/**
 * Переход. Отдельной нодой — чтобы длинную связь на канвасе можно было не тянуть через весь экран.
 *
 * С Э7 переход бывает и **в другой флоу**: заполнен `flow` — управление уходит на стартовую ноду
 * названного графа, а `target` уже ни при чём. На ноду чужого графа не ходим намеренно: id живут в
 * другом документе, редактор их не показывает, и такая связь рвалась бы молча при первой же правке
 * соседнего флоу.
 */
export type GotoNode = NodeBase & { type: "goto"; target: NodeId | null; flow?: string | null };

/** Конец диалога: сказать что-то на прощание и либо вернуть в меню, либо молча закрыть. */
export type EndNode = NodeBase & { type: "end"; text?: string | null; toMenu?: boolean };

export type FlowNode =
  | StartNode
  | MessageNode
  | AskNode
  | MenuNode
  | IfNode
  | ActionNode
  | SubflowNode
  | GotoNode
  | EndNode;

export type FlowNodeType = FlowNode["type"];

/**
 * Граф целиком — то, что лежит JSON'ом в `BotFlow.graph`.
 *
 * `format` — версия формата документа, а не версия графа оператора (та живёт номером строки в БД).
 * Понадобится, когда набор нод поедет: старый документ надо будет прочитать, а не отвергнуть.
 */
export type BotFlowGraph = {
  format: 1;
  /** Какой это флоу: `main`, `invite`, `answer`. Он же `BotFlow.key` и `BotSession.flowKey`. */
  key: string;
  /** Название графа человеку — списком в редакторе. Пусто — покажем ключ. */
  title?: string;
  /** С какой ноды начинается диалог. */
  start: NodeId;
  nodes: FlowNode[];
  /** Перехваты уровня флоу: что разбирается раньше ноды, на которой стоит разговор. */
  intercepts?: FlowIntercept[];
  /** Как в этот флоу попадают снаружи (Э7). Нет объявления — войти в него нечем. */
  entry?: FlowEntry;
};

/**
 * Точка входа флоу (Э7): **объявляется в самом документе**, а не списком где-то сбоку. Пока флоу
 * был один, вход у бота тоже был один — `/start` и перехваты `main`; с несколькими графами вопрос
 * «каким сообщением человек попадает именно сюда» принадлежит графу, как и всё остальное в диалоге.
 *
 * Три вида входа — ровно те, что назвал план:
 *   · `main`     — главный флоу: `/start` без хвоста, первое сообщение незнакомца и возврат «в
 *                  меню» из любого другого графа. Главный ровно один;
 *   · `payloads` — онбординг по ссылке: `t.me/bot?start=invite` приезжает текстом `/start invite`,
 *                  и хвост `invite` ведёт в свой граф, минуя меню;
 *   · `buttons`  — сценарий по кнопке из уведомления: клавиатуру поставил не экран, а рассылка
 *                  (`tg-schedule.ts`, `tg-meetings.ts`), и нажимают её из любого места разговора.
 *
 * Вход работает как перехват (`FlowIntercept`) — тем же порядком разбора и с той же оговоркой про
 * политику ноды: команда (`payloads`) сильнее политики, кнопка — нет, начатую анкету случайное
 * нажатие не бросает.
 */
export type FlowEntry = {
  /** Главный флоу бота. Такой ровно один: в него ведёт `/start` и возврат «в меню». */
  main?: boolean;
  /** Хвосты deeplink-ссылки без `/start`: `invite`, `promo`. */
  payloads?: string[];
  /** Подписи кнопок, которыми в этот флоу входят снаружи из любого места. */
  buttons?: string[];
};

/**
 * Перехват уровня флоу (Э6): текст, который бот разбирает **раньше** ноды, на которой стоит
 * разговор. До Э6 это была россыпь `if` в начале `handleMessage` — `/start`, `/cancel`, кнопки
 * меню посреди квиза, ответ на предложение соперника; теперь это данные графа, как и всё
 * остальное в диалоге.
 *
 * Порядок разбора: собственная кнопка ноды сильнее перехвата (иначе кнопка «Турниры» на экране
 * турнира вела бы не туда, куда нарисовано), а политика ноды может перехват отклонить
 * (`ServicePolicy`). Перехват начинает разговор заново: собранное прошлым диалогом ему не
 * принадлежит.
 */
export type FlowIntercept = {
  /** Что ловим: подпись кнопки или команда вида `/start`. У команды хвост-payload не мешает. */
  match: string;
  /** Куда уводит разговор. `null` — просто оборвать начатое и замолчать. */
  to: NodeId | null;
  /** Что сказать перед переходом. Пусто — молча. */
  text?: string | null;
  /** Срабатывает даже там, где нода велела перехваты не пускать (`/start`, `/cancel`). */
  force?: boolean;
};

/** Ноды, которые ждут ответа человека: на них диалог останавливается и засыпает в сессии. */
const WAITING: ReadonlySet<FlowNodeType> = new Set<FlowNodeType>(["ask", "menu", "subflow"]);

export const isWaiting = (node: FlowNode): boolean => WAITING.has(node.type);

/**
 * Что нода делает со служебной кнопкой. Умолчание — по типу: у модуля внутри разговора есть что
 * терять (собранная анкета), у меню и экранов справок — нечего.
 */
export const servicePolicyOf = (node: FlowNode): ServicePolicy => {
  if ("service" in node && node.service) return node.service;
  return node.type === "subflow" ? "повторить" : "перехват";
};

/**
 * Что из списка ловит этот текст. Сперва точное совпадение по **всему** списку, и только потом
 * команда с хвостом (`/start invite` ловится перехватом `/start`) — иначе более общая запись,
 * стоящая выше, съедала бы свой же частный случай. С Э7 на этом держится и вход по deeplink'у:
 * `/start invite` объявлен точкой входа своего флоу и обязан выиграть у общего `/start` главного.
 */
export function pickMatch<T extends { match: string }>(list: T[], text: string): T | null {
  const items = list.filter((i) => i.match.trim());
  const value = text.trim();
  const exact = items.find((i) => sameLabel(i.match, value));
  if (exact) return exact;
  const prefixed = items.find(
    (i) => i.match.trim().startsWith("/") && value.toLowerCase().startsWith(`${i.match.trim().toLowerCase()} `),
  );
  return prefixed ?? null;
}

/** Перехват этого графа под текст. Роутер (`router.ts`) смотрит шире — по всем живым флоу. */
export const matchIntercept = (graph: BotFlowGraph, text: string): FlowIntercept | null =>
  pickMatch(graph.intercepts ?? [], text);

export const nodeById = (graph: BotFlowGraph, id: NodeId | null | undefined): FlowNode | null =>
  (id ? graph.nodes.find((n) => n.id === id) : null) ?? null;

/** Кнопки ноды — у тех типов, где они бывают. Остальным клавиатуру рисовать нечем. */
export function buttonsOf(node: FlowNode): FlowButton[] {
  if (node.type === "menu") return node.buttons;
  if (node.type === "ask" || node.type === "message") return node.buttons ?? [];
  return [];
}

/**
 * Клавиатура из уже отобранных (видимых) кнопок. Кнопки с одинаковым `row` встают в один ряд —
 * порядок рядов тот, в каком номера впервые встретились; кнопка без номера занимает строку одна.
 * Пусто — `null`: Telegram держит последнюю показанную клавиатуру до отмены, и «нет кнопок» надо
 * сказать явно.
 */
export function rowsOf(buttons: FlowButton[]): string[][] {
  const rows: string[][] = [];
  const byNumber = new Map<number, string[]>();
  for (const b of buttons) {
    if (b.row === undefined || b.row === null) {
      rows.push([b.label]);
      continue;
    }
    const row = byNumber.get(b.row);
    if (row) {
      row.push(b.label);
      continue;
    }
    const fresh = [b.label];
    byNumber.set(b.row, fresh);
    rows.push(fresh);
  }
  return rows;
}

/**
 * Сравнение текста кнопки с тем, что приехало от человека. Регистр и лишние пробелы прощаем: ответ
 * приходит обычным сообщением, и человек мог набрать его руками, а не нажать кнопку.
 */
export const sameLabel = (a: string, b: string): boolean => a.trim().toLowerCase() === b.trim().toLowerCase();

/** Разбор JSON-документа графа. `null` — документ не читается: звать бота на нём нельзя. */
export function parseGraph(raw: string): BotFlowGraph | null {
  try {
    const value = JSON.parse(raw) as BotFlowGraph;
    if (!value || typeof value !== "object" || !Array.isArray(value.nodes) || !value.start) return null;
    return value;
  } catch {
    return null;
  }
}
