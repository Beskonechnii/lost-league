/**
 * Онбординг по ссылке-приглашению (Э7). Со страницы сборки состава человек приходит по
 * `t.me/<bot>?start=invite`, и Telegram присылает боту текст `/start invite` — хвост объявлен
 * точкой входа этого графа, поэтому меню между ссылкой и анкетой не встаёт.
 *
 * Почему своим графом, а не перехватом в главном (так было до Э7): у входа по ссылке своя судьба.
 * Приглашений со временем станет несколько (набор в команду, промо сезона, анкета зрителя), у
 * каждого свой текст и свой первый шаг, и держать их ветками главного меню значит смешивать два
 * разных разговора в одном полотне.
 */
const inviteFlow = (): BotFlowGraph => ({
  format: 1,
  key: INVITE_KEY,
  title: "Онбординг по ссылке",
  entry: { payloads: ["invite"] },
  start: "start",
  nodes: [
    { id: "start", type: "start", title: "/start invite", payload: "invite", next: "reg-do", x: 0, y: 0 },
    // Уже знакомого лиге модуль вернёт сам, поэтому «отменено» ведёт туда же, куда «готово»:
    // объяснение у модуля своё, второе от графа было бы разговором дважды.
    { id: "reg-do", type: "subflow", title: "Регистрация", flow: "регистрация", done: "done", cancel: "done", x: 0, y: 160 },
    { id: "done", type: "end", title: "В меню", toMenu: true, x: 0, y: 320 },
  ],
});

/**
 * Ответ на предложение соперника (Э7) — сценарий, в который входят **кнопкой из уведомления**.
 * Экрана-входа у него нет вовсе: клавиатуру поставила рассылка (`tg-meetings.ts`), и нажимают её
 * из любого места, где человек стоял, хоть через неделю.
 *
 * Это и есть стык исходящего потока с графом: уведомление шлёт `tg-schedule.ts`, а что случится по
 * нажатию — описано здесь, данными (`DECISIONS.md`, 03.09.2026 — почему нод-триггеров не завели).
 */
const answerFlow = (): BotFlowGraph => ({
  format: 1,
  key: ANSWER_KEY,
  title: "Ответ сопернику",
  entry: { buttons: [MR_ACCEPT, MR_COUNTER] },
  start: "start",
  nodes: [
    { id: "start", type: "start", title: "Кнопка из уведомления", next: "answer-do", x: 0, y: 0 },
    { id: "answer-do", type: "subflow", title: "Ответ сопернику", flow: "ответ_сопернику", done: "done", cancel: "done", x: 0, y: 160 },
    { id: "done", type: "end", title: "В меню", toMenu: true, x: 0, y: 320 },
  ],
});

/**
 * Дефолтный набор графов — сидом в коде. Пустая база означает бота со всеми тремя входами, а не
 * бота с одним меню: в `BotFlow` лежат только правки оператора, и правит он их по одному флоу.
 */
export const defaultFlows = (): BotFlowGraph[] => [mainFlow(), inviteFlow(), answerFlow()];

/** Дефолтный граф по ключу. Незнакомый ключ — не дефолт, а новый флоу оператора (`blankFlow`). */
export const defaultFlow = (key: string = FLOW_KEY): BotFlowGraph | null =>
  defaultFlows().find((g) => g.key === key) ?? null;

/**
 * Заготовка нового флоу: вход и конец, между ними пусто. Валидатор такой граф пропускает — он
 * связный и из него есть выход, — но войти в него нечем, пока оператор не объявит точку входа.
 */
export const blankFlow = (key: string): BotFlowGraph => ({
  format: 1,
  key,
  title: "",
  start: "start",
  nodes: [
    { id: "start", type: "start", title: "Вход", next: "end-1", x: 40, y: 40 },
    { id: "end-1", type: "end", title: "В меню", toMenu: true, x: 40, y: 200 },
  ],
});
