// Дефолтный граф диалога бота — сидом в коде, а не строкой в базе. Порядок тот же, что у вопросов
// (`quiz-config.ts`) и настроек (`bot-settings.ts`): в `BotFlow` лежат только правки оператора, а
// пустая база означает бота с обычным флоу, а не бота без флоу.
//
// **Что граф уже ведёт (Э1): первый уровень.** Приветствие и клавиатура меню — здесь; разделы за
// кнопками пока остаются рукописными, поэтому у кнопок `next: null` — «граф показал, дальше
// разбирается старый обработчик» (`tg-quiz.ts`). Так первый уровень можно смотреть и править
// графом, ничего при этом не сломав; разделы переедут нодами-действиями (Э4) и субфлоу (Э5).
//
// Подписи кнопок берём из тех же констант, что и рукописное меню (`menuKeyboard`): пока источников
// два, они обязаны совпадать буква в букву — по подписи кнопки едет и переход по ребру, и разбор в
// старом коде. Единственным источник станет после Э6.

import { FORMS_BUTTON } from "../tg-forms";
import { MENU } from "../tg-menu";
import { REGISTER_BUTTON } from "../tg-register";
import type { BotFlowGraph } from "./types";

/** Ключ единственного пока флоу. Разные графы под разные входы появятся на Э7. */
export const FLOW_KEY = "main";

/** Нода меню — на неё возвращаются концы диалогов, её же показывает /start. */
export const MENU_NODE = "menu";

/**
 * Граф по умолчанию. Повторяет нынешний первый уровень: приветственный текст берётся из реестра
 * вопросов (`settings.menu` — тот же, что правится на /admin/bot), кнопка регистрации показывается
 * тому, кого лига не знает, кнопка анкет — когда открытая анкета есть.
 */
export const defaultFlow = (): BotFlowGraph => ({
  format: 1,
  key: FLOW_KEY,
  start: "start",
  nodes: [
    { id: "start", type: "start", title: "/start", next: MENU_NODE, x: 0, y: 0 },
    {
      id: MENU_NODE,
      type: "menu",
      title: "Главное меню",
      text: "{settings.menu}",
      x: 0,
      y: 120,
      buttons: [
        { label: REGISTER_BUTTON, next: null, when: { left: "ctx.известен", op: "нет" }, row: 0 },
        { label: MENU.profile, next: null, row: 1 },
        { label: MENU.tournaments, next: null, row: 1 },
        { label: FORMS_BUTTON, next: null, when: { left: "ctx.есть_анкеты", op: "=", right: "да" }, row: 2 },
      ],
      // Непонятый текст граф наружу не отдаёт: сегодня бот на него отвечает тем же меню.
      else: MENU_NODE,
    },
  ],
});
