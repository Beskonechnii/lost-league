// Реестр нативных действий: что нода `action` умеет позвать в TS. Граф ведёт навигацию, действия —
// работу: опознать человека, выдать код входа, положить заявку в очередь.
//
// Пока реестр пуст: на Э1 граф ведёт только первый уровень меню, а разделы остаются рукописными
// (`BOT-FLOW-PLAN.md`, Э4 — «Ноды-действия»). Файл заведён вместе с интерпретатором, чтобы у
// действия был один вход, а не по вызову из каждой ноды: имя действия хранится в документе графа,
// и без реестра его нечем проверить ни валидатору (Э3), ни редактору (Э2).

import type { Reply } from "../telegram";
import type { FlowMessage } from "./context";

/** Что действие получает: сообщение, параметры ноды и уже собранные переменные диалога. */
export type ActionInput = {
  msg: FlowMessage;
  params: Record<string, string>;
  vars: Record<string, string>;
};

/**
 * Что действие возвращает: реплики бота, новые переменные и по какому выходу идти дальше.
 * `ok: false` — не «упало», а «не получилось»: у ноды для этого есть выход `ошибка`. Настоящее
 * падение остаётся исключением — его ловит интерпретатор.
 */
export type ActionResult = { ok: boolean; replies?: Reply[]; vars?: Record<string, string> };

export type FlowAction = {
  /** Подпись в палитре редактора. */
  label: string;
  /** Какие параметры нода обязана задать. */
  params?: string[];
  /** Что кладёт в `vars.*` — валидатору, чтобы он знал про эти имена. */
  provides?: string[];
  run: (input: ActionInput) => Promise<ActionResult>;
};

/** Действия по именам. Имя лежит в документе графа (`ActionNode.action`). */
export const FLOW_ACTIONS: Record<string, FlowAction> = {};
