// Зоны выхода из группы: чистые правила и цвета, без обращений к БД.
// Отдельно от group-stage.ts намеренно — тот тянет Prisma, а это нужно и клиентским компонентам
// (сетка групп). Та же развилка, что у openai-images.ts (сервер) и image-options.ts (данные).

/** Куда команда уходит из группы. Порядок и цвета одинаковы везде, где показываем группу. */
export type Qualification = "upper" | "lower" | "out";

/**
 * Цвета зон приехали из Кита (артборд «Турнирная таблица», блок «Зоны и легенда»): рейка зоны
 * заливается ГРАДИЕНТОМ, а не плоским цветом — как и всё в Ките, где свет идёт ↖. До Э5 здесь
 * стояли `emerald-400/amber-400/rose-400` — остаток тёмной темы: на бумаге #E7E3D8 такой текст
 * даёт около 2:1 и не читается. Теперь `text` — тёмная пара того же оттенка (мятный ink Кита,
 * охра и кирпич из его же алертов), а `bar` — градиент рейки; `marker` остался плоским для мест,
 * где нужна точка, а не полоса.
 */
export const QUALIFICATION: Record<
  Qualification,
  { label: string; text: string; marker: string; bar: string }
> = {
  upper: {
    label: "Верхняя сетка",
    text: "text-[var(--accent-ink)]",
    marker: "bg-[#7FC3A4]",
    bar: "linear-gradient(135deg,#B7E4CD,#7FC3A4)",
  },
  lower: {
    label: "Нижняя сетка",
    text: "text-[var(--color-warn-ink)]",
    marker: "bg-[#E2BC63]",
    bar: "linear-gradient(135deg,#F3DEA6,#E2BC63)",
  },
  out: {
    label: "Вылет",
    text: "text-[var(--color-err-ink)]",
    marker: "bg-[#DE9494]",
    bar: "linear-gradient(135deg,#F0C4C4,#DE9494)",
  },
};

/**
 * Регламент: 1–4 место — верхняя сетка, дальше зависит от дивизиона. В D1 (8 команд в группе) два
 * последних вылетают, в D2 вылета из группы нет — все непопавшие в верхнюю падают в нижнюю.
 *
 * Раньше это решалось сравнением имени дивизиона со строкой «Division 2»: в новом турнире с другими
 * именами правило молча стало бы D1-овским. Теперь признак живёт у дивизиона (`Division.relegation`),
 * а сюда приходит булевым — модуль остаётся чистым и годится клиентским компонентам.
 *
 * Считаем от низа, а не по фиксированным местам: в группе может быть не восемь команд.
 */
export function qualificationOf(place: number, groupSize: number, relegation: boolean): Qualification {
  if (place <= 4) return "upper";
  if (!relegation) return "lower";
  return place > groupSize - 2 ? "out" : "lower";
}

/**
 * Очки за серию Bo3. Формула выведена из таблицы сезона и сошлась на всех командах группы A
 * первого дивизиона (ГУЗЛИКИ 15, Ethereal 15, 5KN 2), поэтому считаем её правилом лиги:
 * 2:0 → 3, 2:1 → 2, 1:2 → 1, 0:2 → 0. Идея — «сухая» победа дороже, а взятая карта не пропадает.
 */
export function seriesPoints(own: number, opp: number) {
  if (own > opp) return opp === 0 ? 3 : 2;
  return own === 0 ? 0 : 1;
}
