// Нормы картинок профилей: под какую форму режется каждый слот загрузки.
//
// Зачем. Раньше файл ложился в public/uploads как есть, а слоты на страницах квадратные:
// лого 3:2 в квадрате получало поля с одной стороны, портрет 9:16 — object-cover резал голову.
// Форму задавала вёрстка, а картинка про неё не знала. Теперь наоборот: у каждого слота есть
// норма (размер, соотношение, способ вписывания), файл приводится к ней ещё в браузере
// (см. app/_components/image-fit.tsx), и в uploads попадает уже готовый кадр.
//
// Одно место правды: этими же цифрами рисуется рамка подгонки, превью в форме и подсказка
// оператору. Меняется норма — меняются все трое разом.

/** Слот = вид профиля + поле. Строка, а не пара, чтобы её можно было положить в проп одним значением. */
export type ImageSlot =
  | "team-logo"
  | "team-wordmark"
  | "team-photo"
  | "team-banner"
  | "player-photo"
  | "player-banner";

export type ImageNorm = {
  /** Размер итогового файла в пикселях — он же рамка подгонки. */
  width: number;
  height: number;
  /**
   * Как кадр ложится в рамку по умолчанию.
   * cover — рамка заполняется целиком, лишнее срезается (портреты, баннеры, фото);
   * contain — картинка вписывается вся, по краям прозрачные поля (эмблема, надпись).
   */
  fit: "cover" | "contain";
  /**
   * png хранит прозрачность — она нужна эмблемам и вырезкам «по грудь», иначе на подложке
   * появится белый прямоугольник. Баннеру прозрачность не нужна, а вес важен → webp.
   */
  format: "png" | "webp";
  /** Поля вокруг рисунка для contain, доля от меньшей стороны: эмблема не должна упираться в край. */
  padding?: number;
  /** Подсказка под полем — что это за картинка и в какой она форме. */
  hint: string;
};

