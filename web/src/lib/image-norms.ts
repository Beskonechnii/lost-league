/** MIME итогового файла — им же canvas.toBlob решает, чем кодировать. */
export const mimeOf = (norm: ImageNorm) => (norm.format === "png" ? "image/png" : "image/webp");

/** Соотношение сторон слота — для CSS aspect-ratio превью и рамки подгонки. */
export const ratioOf = (norm: ImageNorm) => `${norm.width} / ${norm.height}`;
