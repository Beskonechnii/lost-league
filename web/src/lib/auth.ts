// --- Что закрываем ---
//
// Правило: **закрыто всё, что пишет** — плюс разбор матча, который переехал в операторскую.
// Читать лигу можно без входа: публичная таблица и ростер открыты, их и встраивают в лендинг.

/** Страницы служебной части: существуют только чтобы что-то менять или тратить деньги. */
const PROTECTED_PAGES = [
  "/studio", // генерация картинок через OpenAI — платная, чужим тут делать нечего
  "/admin", // правка ростера, роли, заявки — всё, что живёт в группе (admin)
  "/underbeer", // сборка шоу-команд — операторский инструмент эфира (публичен только /overlay/*)
  "/match", // разбор матча — операторский инструмент, убран с лендинга и закрыт
];

/** Нужны ли права администратора для этого запроса. Одно место правды — зовётся из proxy и из роутов. */
export function needsAdmin(pathname: string, method: string): boolean {
  // Исключения из «читать можно всем». Первое: полка выгруженных постгеймов — черновики
  // оператора, а не факт о лиге. Прятать её в интерфейсе и раздавать списком через API — половина работы.
  if (pathname.startsWith("/api/postgame/archive")) return true;

  // Второе: выгрузка ответов анкеты — это люди, их контакты и то, что
  // они написали организатору. Роут проверяет право и сам, но пускать до него посторонних незачем.
  if (pathname.startsWith("/api/quizzes/")) return true;

  // Исключение третье, обратное: чат игроков. Писать в него — обычное дело для игрока, а не для
  // администратора, поэтому общее правило «POST в /api только админу» здесь не работает. Право
  // проверяет сам роут (src/lib/chat.ts: аккаунт должен быть одобрен и привязан к профилю).
  if (pathname.startsWith("/api/chat/")) return false;

  // Любая запись через API: POST/PATCH/PUT/DELETE. Чтение (GET) остаётся публичным.
  if (pathname.startsWith("/api/")) return method !== "GET" && method !== "HEAD";

  // Граница «читают/пишут» видна прямо в адресе: всё под этими префиксами требует роли.
  return PROTECTED_PAGES.some((p) => pathname === p || pathname.startsWith(`${p}/`));
}
