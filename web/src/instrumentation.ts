// Разовая инициализация процесса Node (Next 16, `register` зовётся один раз на старте сервера).
//
// Зачем он появился: часы драфта в лобби считает сервер, и на срок хода взводится будильник в
// памяти процесса (src/lib/lobby.ts). Перезапуск память теряет, а срок — нет, он лежит в БД.
// Здесь будильники поднимаются заново, иначе идущий драфт после деплоя стоял бы до первого
// обращения к комнате.

export async function register() {
  // Edge-рантайм и сборка сюда тоже заглядывают, а прислониться к БД могут не всегда: часы —
  // дело серверного процесса, и падать из-за них на сборке нечему.
  if (process.env.NEXT_RUNTIME !== "nodejs") return;
  try {
    const { armLobbyTimers } = await import("@/lib/lobby");
    await armLobbyTimers();
  } catch (e) {
    console.error("[lobby] не удалось поднять часы идущих драфтов:", e);
  }
}
